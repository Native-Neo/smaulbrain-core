"""Reduced-precision storage for cached activations and gradients.

The runtime has no separate activation-cache object: every differentiable
operation keeps its result (and, for a few primitives, a derived array) alive in
the autograd graph until backward finishes.  This module provides the storage
formats used at that boundary.

BF16 is stored as the raw 16-bit IEEE bfloat16 pattern in ``uint16`` arrays.
NumPy has no native bfloat16 dtype, so this is the actual two-byte format, not
a float32 array that was merely cast through a temporary.  Decoding widens the
bits back to float32 with a shift and view.  Rounding is round-to-nearest-even
and infinities/NaNs are preserved.

INT8 uses a dynamically calculated symmetric per-tensor scale,
``scale = max(abs(x)) / 127`` (``1.0`` for an all-zero tensor), rounds to
nearest, keeps codes in ``[-127, 127]``, and dequantizes as
``code * scale``.  A scale derived from the tensor makes clipping redundant,
so that fast path omits it; caller-supplied scales are clipped.  Non-finite
tensors are rejected rather than silently saturated.
"""
from __future__ import annotations

import contextlib
import sys

import numpy as np

ACTIVATION_STORAGE_MODES = ("fp32", "bf16", "int8")
GRADIENT_STORAGE_MODES = ("fp32", "bf16")

# Arrays smaller than this are not worth wrapping: the Python object and the
# extra conversion cost outweigh the saved bytes.  This is a threshold on the
# logical float32 size.
DEFAULT_MIN_ACTIVATION_BYTES = 1024
INT8_MAX = 127.0


def validate_activation_storage(mode: str) -> str:
    value = str(mode).lower()
    if value not in ACTIVATION_STORAGE_MODES:
        raise ValueError(
            f"activation storage must be one of {ACTIVATION_STORAGE_MODES}, got {mode!r}")
    return value


def validate_gradient_storage(mode: str) -> str:
    value = str(mode).lower()
    if value not in GRADIENT_STORAGE_MODES:
        raise ValueError(
            f"gradient storage must be one of {GRADIENT_STORAGE_MODES}, got {mode!r}")
    return value


# ---------------------------------------------------------------------------
# BF16 codec
# ---------------------------------------------------------------------------
def _bf16_encode_u32(x) -> np.ndarray:
    """Portable fallback for big-endian hosts."""
    bits = x.view(np.uint32)
    # RNE: add half an ulp plus the retained LSB (ties round to even).
    rounded = bits + np.uint32(0x7FFF) + ((bits >> np.uint32(16)) & np.uint32(1))
    high = (rounded >> np.uint32(16)).astype(np.uint16)
    # The addition above can carry a NaN payload into infinity.  Preserve the
    # original high half for every non-finite value instead.
    nonfinite = (bits & np.uint32(0x7F800000)) == np.uint32(0x7F800000)
    if np.any(nonfinite):
        high[nonfinite] = (bits[nonfinite] >> np.uint32(16)).astype(np.uint16)
    return high


def _bf16_encode_specials(x) -> np.ndarray:
    """RNE encoder that keeps NaN/Inf payloads intact.

    The carry generated by ordinary round-to-nearest-even can change a NaN
    payload into infinity.  This slower path masks the increment for every
    non-finite input; the common finite path in :func:`bf16_encode` does not
    pay for that mask.
    """
    halves = x.view(np.uint16).reshape(x.shape + (2,))
    lo = halves[..., 0]
    hi = halves[..., 1]
    nonfinite = (hi & np.uint16(0x7F80)) == np.uint16(0x7F80)
    bump = (lo > np.uint16(0x8000)) | (
        (lo == np.uint16(0x8000)) & ((hi & np.uint16(1)) != 0))
    bump &= ~nonfinite
    high = np.array(hi, dtype=np.uint16, order="C", copy=True)
    high += bump
    return high


def bf16_encode(array) -> np.ndarray:
    """Return the round-to-nearest-even bfloat16 bit pattern of ``array``."""
    x = np.ascontiguousarray(array, dtype=np.float32)
    if sys.byteorder != "little":
        return _bf16_encode_u32(x)
    if not np.isfinite(x).all():
        return _bf16_encode_specials(x)

    # Finite inputs need no special-value mask.  For narrow tensors the uint32
    # route is substantially faster because it avoids the strided low/high
    # half view; for wider tensors the uint16 view has better memory locality.
    if x.nbytes <= 128 * 1024:
        bits = x.view(np.uint32)
        rounded = bits + np.uint32(0x7FFF)
        rounded += (bits >> np.uint32(16)) & np.uint32(1)
        return (rounded >> np.uint32(16)).astype(np.uint16)

    halves = x.view(np.uint16).reshape(x.shape + (2,))
    lo = halves[..., 0]
    hi = halves[..., 1]
    # Round values strictly above the midpoint up.  Exact ties are rare
    # (roughly one in 2**16 float32 values), so handle them with a compact
    # flat-index pass instead of materializing a full tie mask.
    high = hi + (lo > np.uint16(0x8000))
    ties = np.flatnonzero(lo == np.uint16(0x8000))
    if ties.size:
        tied_hi = high.reshape(-1)[ties]
        odd = (tied_hi & np.uint16(1)) != 0
        if np.any(odd):
            high.reshape(-1)[ties[odd]] += np.uint16(1)
    return high


def _bf16_decode_u32(high) -> np.ndarray:
    return (high.astype(np.uint32) << np.uint32(16)).view(np.float32)


def bf16_decode(bits) -> np.ndarray:
    """Widen bfloat16 bit patterns to a new float32 array."""
    high = np.ascontiguousarray(bits, dtype=np.uint16)
    if sys.byteorder != "little":
        return _bf16_decode_u32(high)
    out = np.zeros(high.shape + (2,), dtype=np.uint16)
    out[..., 1] = high
    return out.view(np.float32).reshape(high.shape)


def bf16_roundtrip(array) -> np.ndarray:
    return bf16_decode(bf16_encode(array))


# ---------------------------------------------------------------------------
# INT8 codec
# ---------------------------------------------------------------------------
def int8_scale(array) -> np.float32:
    """Symmetric per-tensor scale; zero tensors get a harmless unit scale."""
    x = np.asarray(array)
    if x.size == 0:
        return np.float32(1.0)
    # A non-finite maximum catches every NaN/Inf without allocating a second
    # boolean array the size of the activation.
    amax = float(np.max(np.abs(x)))
    if not np.isfinite(amax):
        raise ValueError("cannot int8-quantize a tensor containing NaN or infinity")
    if not amax > 0.0:
        return np.float32(1.0)
    scale = np.float32(amax / INT8_MAX)
    if not scale > 0.0:
        # The division can underflow for all-subnormal tensors.  Fall back to
        # the smallest positive float32 so quantization still round-trips.
        scale = np.nextafter(np.float32(0.0), np.float32(1.0))
    return scale


def int8_quantize(array, scale=None):
    """Return ``(codes, scale)`` with explicit rounding and clipping."""
    a = np.ascontiguousarray(array, dtype=np.float32)
    clip = scale is not None
    if scale is None:
        scale = int8_scale(a)
    else:
        if a.size and not np.isfinite(float(np.max(np.abs(a)))):
            raise ValueError("cannot int8-quantize a tensor containing NaN or infinity")
        scale = np.float32(scale)
        if not np.isfinite(scale) or not scale > 0.0:
            raise ValueError("int8 scale must be finite and positive")
    scaled = a / scale
    np.rint(scaled, out=scaled)
    if clip:
        # With a caller-supplied scale, input values may exceed the INT8 range.
        # A scale derived from this tensor already guarantees |scaled| <= 127;
        # clipping there is a full extra pass over the activation.
        np.clip(scaled, -INT8_MAX, INT8_MAX, out=scaled)
    codes = scaled.astype(np.int8)
    return codes, scale


def int8_dequantize(codes, scale) -> np.ndarray:
    out = np.ascontiguousarray(codes, dtype=np.int8).astype(np.float32)
    out *= np.float32(scale)
    return out


# ---------------------------------------------------------------------------
# Stored activation
# ---------------------------------------------------------------------------
class StoredArray:
    """A compressed activation: ``dequantize`` returns a fresh float32 array."""

    __slots__ = ("mode", "shape", "codes", "scale", "nbytes")

    def __init__(self, mode, shape, codes, scale=None):
        self.mode = mode
        self.shape = tuple(int(s) for s in shape)
        self.codes = codes
        self.scale = scale
        meta = 0 if scale is None else np.asarray(scale).nbytes
        self.nbytes = int(codes.nbytes + meta)

    @property
    def storage_dtype(self):
        return self.mode

    @property
    def logical_dtype(self):
        return np.dtype(np.float32)

    def dequantize(self) -> np.ndarray:
        if self.mode == "bf16":
            out = bf16_decode(self.codes)
        elif self.mode == "int8":
            out = int8_dequantize(self.codes, self.scale)
        else:  # pragma: no cover - constructor rejects this
            raise ValueError(f"unsupported stored activation mode {self.mode!r}")
        return out.reshape(self.shape)

    @classmethod
    def compress(cls, array, mode) -> "StoredArray":
        mode = validate_activation_storage(mode)
        if mode == "fp32":
            raise ValueError("fp32 is not a compressed storage mode")
        a = np.ascontiguousarray(array, dtype=np.float32)
        if mode == "bf16":
            return cls(mode, a.shape, bf16_encode(a))
        codes, scale = int8_quantize(a)
        return cls(mode, a.shape, codes, scale)


# ---------------------------------------------------------------------------
# Activation-storage policy (process-global context)
# ---------------------------------------------------------------------------
_activation_mode = "fp32"
_min_activation_bytes = DEFAULT_MIN_ACTIVATION_BYTES


def get_activation_storage():
    return _activation_mode


@contextlib.contextmanager
def activation_storage(mode="bf16", min_bytes=None):
    """Store differentiable op results in ``mode`` while the context is active."""
    global _activation_mode, _min_activation_bytes
    previous_mode = _activation_mode
    previous_min = _min_activation_bytes
    _activation_mode = validate_activation_storage(mode)
    if min_bytes is not None:
        _min_activation_bytes = int(min_bytes)
    try:
        yield
    finally:
        _activation_mode = previous_mode
        _min_activation_bytes = previous_min


def should_store(array, cache=True) -> bool:
    if not cache or _activation_mode == "fp32":
        return False
    if not isinstance(array, np.ndarray) or not np.issubdtype(array.dtype, np.floating):
        return False
    if array.dtype != np.float32:
        return False
    return int(array.nbytes) >= int(_min_activation_bytes)


# ---------------------------------------------------------------------------
# Persistent gradient storage
# ---------------------------------------------------------------------------
class PackedGradient:
    """A BF16 gradient buffer with an explicit float32 decode boundary.

    Accumulation happens in float32 inside ``Tensor.backward``; this container
    is created once after a leaf's gradient is complete.  Consumers decode one
    parameter at a time, so no full float32 copy of the gradient set is kept.
    """

    __slots__ = ("codes", "shape", "nbytes")

    def __init__(self, codes, shape):
        self.codes = np.ascontiguousarray(codes, dtype=np.uint16)
        self.shape = tuple(int(s) for s in shape)
        self.nbytes = int(self.codes.nbytes)

    @property
    def storage_dtype(self):
        return "bf16"

    @property
    def dtype(self):
        return np.dtype(np.float32)

    @property
    def ndim(self):
        return len(self.shape)

    @property
    def size(self):
        return int(np.prod(self.shape, dtype=np.int64))

    @classmethod
    def compress(cls, array, encoder=None) -> "PackedGradient":
        a = np.ascontiguousarray(array, dtype=np.float32)
        codes = (encoder or bf16_encode)(a)
        return cls(codes, a.shape)

    def dequantize(self) -> np.ndarray:
        return bf16_decode(self.codes).reshape(self.shape)

    def copy(self) -> np.ndarray:
        return self.dequantize()

    def astype(self, dtype, copy=True):
        return self.dequantize().astype(dtype, copy=copy)

    def zero_(self):
        self.codes[...] = 0

    def mul_(self, scale):
        self.codes = bf16_encode(self.dequantize() * np.float32(scale))

    def __array__(self, dtype=None, copy=None):
        if copy is False:
            raise ValueError("PackedGradient must be decoded into a new array")
        value = self.dequantize()
        if dtype is None:
            return value
        # ``asarray`` avoids a second full-size temporary when the caller asks
        # for float32, which is already the decoded dtype.
        return np.asarray(value, dtype=dtype)

    def __len__(self):
        return self.shape[0]

    def __getitem__(self, key):
        return self.dequantize()[key]

    def __setitem__(self, key, value):
        dense = self.dequantize()
        dense[key] = value
        self.codes = bf16_encode(dense)

    def __imul__(self, scale):
        self.mul_(scale)
        return self

    def __repr__(self):
        return f"PackedGradient(shape={self.shape}, storage=bf16)"


_gradient_mode = "fp32"


def get_gradient_storage():
    return _gradient_mode


@contextlib.contextmanager
def gradient_storage(mode="bf16"):
    """Store completed leaf gradient buffers in ``mode`` inside the context."""
    global _gradient_mode
    previous = _gradient_mode
    _gradient_mode = validate_gradient_storage(mode)
    try:
        yield
    finally:
        _gradient_mode = previous


def gradient_array(value):
    """Return a float32 ndarray without mutating a packed gradient buffer."""
    if isinstance(value, PackedGradient):
        return value.dequantize()
    return np.asarray(value)


def store_gradient(value, mode):
    mode = validate_gradient_storage(mode)
    if mode == "fp32":
        return gradient_array(value).copy()
    if isinstance(value, PackedGradient):
        return value
    return PackedGradient.compress(value)


def scale_gradient(value, scale):
    """Scale a packed or plain gradient, returning the same storage kind."""
    if isinstance(value, PackedGradient):
        value.mul_(scale)
        return value
    value *= scale
    return value


def zero_gradient(value):
    if isinstance(value, PackedGradient):
        value.zero_()
    else:
        value[...] = 0
